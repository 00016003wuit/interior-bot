/**
 * Sanitizes a string input by trimming whitespace and truncating to max length.
 * Returns empty string for non-string inputs.
 * @param {*} str - Input value to sanitize
 * @param {number} [maxLen=500] - Maximum allowed character length
 * @returns {string} Sanitized string
 */
function sanitizeStr(str, maxLen = 500) {
  if (typeof str !== "string") return "";
  return str.trim().slice(0, maxLen);
}

/**
 * Validates a phone number string against international format.
 * Accepts formats: +998901234567, +998 90 123-45-67, (90) 123-4567
 * @param {string} phone - Phone number to validate
 * @returns {boolean} True if phone matches valid format (7-15 digits)
 */
function isValidPhone(phone) {
  if (!phone || typeof phone !== "string") return false;
  const cleaned = phone.replace(/[\s\-()]/g, "");
  return /^\+?\d{7,15}$/.test(cleaned);
}

/**
 * Checks if a value is present in a list of allowed values.
 * @param {*} val - Value to check
 * @param {Array} validList - Array of allowed values
 * @returns {boolean} True if val is in validList
 */
function validateEnum(val, validList) {
  return validList.includes(val);
}

/**
 * Validates and filters a priorities array against known priority keys.
 * Returns empty array for non-array input, caps at 8 items max.
 * @param {Array} arr - Array of priority key strings
 * @returns {string[]} Filtered array of valid priority keys
 */
function validatePriorities(arr) {
  if (!Array.isArray(arr)) return [];
  return arr.filter(p => VALID_PRIORITIES.includes(p)).slice(0, 8);
}

