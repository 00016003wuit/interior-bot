/**
 * Loads and parses a JSON file from the data directory.
 * @param {string} filename - Name of the JSON file (e.g. "users.json")
 * @param {Object} fallback - Default value if file doesn't exist or parse fails
 * @returns {Object} Parsed JSON data or fallback value
 */
function loadJSON(filename, fallback = {}) {
  try { return JSON.parse(fs.readFileSync(path.join(DATA_DIR, filename), "utf8")); }
  catch { return fallback; }
}

/**
 * Saves data as a JSON file in the data directory.
 * @param {string} filename - Name of the JSON file
 * @param {Object} data - Data to serialize and write
 */
function saveJSON(filename, data) {
  fs.writeFileSync(path.join(DATA_DIR, filename), JSON.stringify(data, null, 2));
}

/**
 * Retrieves a user record by Telegram user ID.
 * @param {number|string} userId - Telegram user ID
 * @returns {Object|null} User object or null if not found
 */
function getUser(userId) {
  return loadJSON("users.json")[String(userId)] || null;
}

/**
 * Creates or updates a user record with the given fields.
 * Merges new fields with existing data and adds updatedAt timestamp.
 * @param {number|string} userId - Telegram user ID
 * @param {Object} fields - Fields to create/update (e.g. { phone, lang, prefs })
 * @returns {Object} The saved user object
 */
function saveUser(userId, fields) {
  const users = loadJSON("users.json");
  const existing = users[String(userId)] || {};
  users[String(userId)] = { ...existing, ...fields, updatedAt: new Date().toISOString() };
  saveJSON("users.json", users);
  return users[String(userId)];
}

/**
 * Gets the total number of designs generated by a user.
 * @param {number|string} userId - Telegram user ID
 * @returns {number} Number of designs used (0 if no record)
 */
function getUsage(userId) {
  return loadJSON("usage.json")[String(userId)] || 0;
}

/**
 * Increments the usage counter for a user by 1.
 * @param {number|string} userId - Telegram user ID
 * @returns {number} Updated usage count after increment
 */
function incUsage(userId) {
  const data = loadJSON("usage.json");
  data[String(userId)] = (data[String(userId)] || 0) + 1;
  saveJSON("usage.json", data);
  return data[String(userId)];
}

/**
 * Gets the number of paid (purchased) design credits available to a user.
 * @param {number|string} userId - Telegram user ID
 * @returns {number} Paid credits remaining
 */
function getPaidCredits(userId) {
  return loadJSON("credits.json")[String(userId)] || 0;
}

/**
 * Adds purchased credits to a user's balance.
 * @param {number|string} userId - Telegram user ID
 * @param {number} amount - Credits to add
 * @returns {number} New paid credits balance
 */
function addPaidCredits(userId, amount) {
  const data = loadJSON("credits.json");
  data[String(userId)] = (data[String(userId)] || 0) + amount;
  saveJSON("credits.json", data);
  return data[String(userId)];
}

/**
 * Consumes one paid credit from a user's balance, if available.
 * @param {number|string} userId - Telegram user ID
 * @returns {boolean} True if a credit was consumed, false if balance was zero
 */
function consumePaidCredit(userId) {
  const data = loadJSON("credits.json");
  const cur = data[String(userId)] || 0;
  if (cur <= 0) return false;
  data[String(userId)] = cur - 1;
  saveJSON("credits.json", data);
  return true;
}

/**
 * Computes a user's total available designs (free remaining + paid credits).
 * @param {number|string} userId
 * @returns {{used: number, limit: number, freeRemaining: number, paidCredits: number, remaining: number}}
 */
function getUserUsage(userId) {
  const used = getUsage(userId);
  const paidCredits = getPaidCredits(userId);
  const freeRemaining = Math.max(0, FREE_LIMIT - used);
  return {
    used,
    limit: FREE_LIMIT,
    freeRemaining,
    paidCredits,
    remaining: freeRemaining + paidCredits,
  };
}

// Sessions (in-memory, lost on restart — suitable for active design sessions)
const sessions = new Map(); // userId → { photos[], roomType, results[], expiresAt }
const SESSION_TTL = 30 * 60 * 1000; // 30 min

/**
 * Retrieves an active session for a user. Expired sessions are auto-deleted.
 * @param {number|string} userId - Telegram user ID
 * @returns {Object|null} Session data or null if expired/missing
 */
function getSession(userId) {
  const s = sessions.get(String(userId));
  if (!s) return null;
  if (Date.now() > s.expiresAt) { sessions.delete(String(userId)); return null; }
  return s;
}

/**
 * Creates or replaces the active session for a user with a 30-minute TTL.
 * @param {number|string} userId - Telegram user ID
 * @param {Object} data - Session data (photos, roomType, results)
 */
function setSession(userId, data) {
  sessions.set(String(userId), { ...data, expiresAt: Date.now() + SESSION_TTL });
}

/**
 * Removes a user's active session from memory.
 * @param {number|string} userId - Telegram user ID
 */
function clearSession(userId) {
  sessions.delete(String(userId));
}

